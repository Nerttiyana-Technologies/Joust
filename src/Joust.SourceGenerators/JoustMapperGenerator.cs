using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace Joust.SourceGenerators;

/// <summary>
/// Generates AOT-friendly <c>IRowMapper&lt;T&gt;</c> implementations for types annotated with
/// <c>[JoustRecord]</c>, and registers them at module-initialization time. This removes reflection
/// and runtime delegate compilation from the mapping path entirely.
/// </summary>
[Generator]
public sealed class JoustMapperGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var sources = context.SyntaxProvider.ForAttributeWithMetadataName(
            "Joust.JoustRecordAttribute",
            predicate: static (node, _) => node is ClassDeclarationSyntax,
            transform: static (ctx, _) => BuildSource((INamedTypeSymbol)ctx.TargetSymbol));

        context.RegisterSourceOutput(sources, static (spc, item) =>
            spc.AddSource(item.HintName, SourceText.From(item.Source, Encoding.UTF8)));
    }

    private static (string HintName, string Source) BuildSource(INamedTypeSymbol type)
    {
        var fully = type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
        var ns = type.ContainingNamespace.IsGlobalNamespace
            ? "JoustGenerated"
            : type.ContainingNamespace.ToDisplayString();

        var props = type.GetMembers()
            .OfType<IPropertySymbol>()
            .Where(p => !p.IsStatic
                        && p.DeclaredAccessibility == Accessibility.Public
                        && p.GetMethod is not null
                        && p.SetMethod is not null
                        && !p.IsIndexer)
            .Select(p => (Column: ColumnName(p), Name: p.Name, Type: p.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)))
            .ToImmutableArray();

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine($"namespace {ns}");
        sb.AppendLine("{");
        sb.AppendLine($"    file sealed class {type.Name}RowMapper : global::Joust.Mapping.IRowMapper<{fully}>");
        sb.AppendLine("    {");
        sb.AppendLine($"        public global::System.Collections.Generic.Dictionary<string, object?> ToRow({fully} item)");
        sb.AppendLine("        {");
        sb.AppendLine($"            var row = new global::System.Collections.Generic.Dictionary<string, object?>({props.Length}, global::System.StringComparer.Ordinal);");
        foreach (var p in props)
            sb.AppendLine($"            row[\"{p.Column}\"] = item.{p.Name};");
        sb.AppendLine("            return row;");
        sb.AppendLine("        }");
        sb.AppendLine();
        sb.AppendLine($"        public {fully} FromRow(global::System.Collections.Generic.IReadOnlyDictionary<string, object?> row)");
        sb.AppendLine("        {");
        sb.AppendLine($"            var item = new {fully}();");
        foreach (var p in props)
        {
            sb.AppendLine($"            if (row.TryGetValue(\"{p.Column}\", out var v_{p.Name}) && v_{p.Name} is not null)");
            sb.AppendLine($"                item.{p.Name} = global::Joust.Mapping.MapConvert.To<{p.Type}>(v_{p.Name}!);");
        }
        sb.AppendLine("            return item;");
        sb.AppendLine("        }");
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine($"    file static class {type.Name}MapperModuleInit");
        sb.AppendLine("    {");
        sb.AppendLine("        [global::System.Runtime.CompilerServices.ModuleInitializer]");
        sb.AppendLine($"        public static void Init() => global::Joust.Mapping.MapperRegistry.Register(new {type.Name}RowMapper());");
        sb.AppendLine("    }");
        sb.AppendLine("}");

        return ($"{ns}.{type.Name}.Mapper.g.cs", sb.ToString());
    }

    private static string ColumnName(IPropertySymbol property)
    {
        var column = property.GetAttributes()
            .FirstOrDefault(a => a.AttributeClass?.ToDisplayString() == "Joust.ColumnAttribute");
        if (column is { ConstructorArguments.Length: > 0 } &&
            column.ConstructorArguments[0].Value is string name && name.Length > 0)
            return name;

        return ToSnakeCase(property.Name);
    }

    private static string ToSnakeCase(string name)
    {
        if (string.IsNullOrEmpty(name))
            return name;

        var sb = new StringBuilder(name.Length + 8);
        for (int i = 0; i < name.Length; i++)
        {
            char c = name[i];
            if (char.IsUpper(c))
            {
                bool prevLower = i > 0 && char.IsLower(name[i - 1]);
                bool nextLower = i + 1 < name.Length && char.IsLower(name[i + 1]);
                if (i > 0 && (prevLower || nextLower))
                    sb.Append('_');
                sb.Append(char.ToLowerInvariant(c));
            }
            else
            {
                sb.Append(c);
            }
        }
        return sb.ToString();
    }
}
